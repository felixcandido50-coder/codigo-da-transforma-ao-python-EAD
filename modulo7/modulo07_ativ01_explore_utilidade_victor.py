# Função que recebe dois valores (a e b) e calcula a soma entre eles
def somar(a, b):
    """Retorna a soma de dois números."""
    return a + b


# Função que recebe dois valores (a e b) e calcula a diferença (subtração) entre eles
def subtrair(a, b):
    """Retorna a subtração de dois números."""
    return a - b


# Função que recebe a base e o expoente para calcular a potenciação (base elevada ao expoente)
def potencia(base, expoente):
    """Retorna a base elevada ao expoente."""
    return base**expoente